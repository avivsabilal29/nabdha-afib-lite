def turunkan_ambang(arr, cls, kisi1, kisi2):
    """Turunkan pasangan ambang gerbang AND pada deret itu sendiri.

    Aturan pemilihan: akurasi terbesar, lalu Youden terbesar, lalu ambang terkecil, supaya hasilnya
    satu pasangan saja dan tidak bergantung urutan sapuan. Ketika beberapa pasangan mencapai akurasi
    terbesar, jumlah pasangan yang seri dan rentang ambang entropinya dilaporkan terpisah.
    """
    af = cls == "AFIB"
    seri = []
    for t1 in kisi1:
        m1 = arr[:, 1] > t1
        for t2 in kisi2:
            p = m1 & (arr[:, 3] > t2)
            se = float(p[af].mean())
            sp = float(1.0 - p[~af].mean())
            acc = float((p == af).mean())
            youden = se + sp - 1.0
            seri.append((acc, youden, float(t1), float(t2), se, sp))
    acc_max = max(s[0] for s in seri)
    seri = [s for s in seri if s[0] >= acc_max - 1e-12]
    seri.sort(key=lambda s: (-s[1], s[2], s[3]))
    acc, youden, t1, t2, se, sp = seri[0]
    return dict(t1=t1, t2=t2, kepekaan=se, spesifisitas=sp, akurasi=acc, youden=youden,
                jendela=int(cls.size), afib=int(af.sum()), n=int((~af).sum()),
                seri=len(seri), t2_min=min(s[3] for s in seri), t2_max=max(s[3] for s in seri),
                t1_max=max(s[2] for s in seri))

