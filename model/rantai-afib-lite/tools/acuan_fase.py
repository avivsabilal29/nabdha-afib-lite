def nilai_denyut(beats, qh, th, mulai):
    """Nilai satu deret denyut: QRS tertangkap, QRS hilang, deteksi palsu gelombang T dan lain."""
    b = np.array([int(x) for x in beats if int(x) >= mulai], dtype=np.int64)
    rq = qh[qh >= mulai]
    rt = th[th >= mulai]
    tertangkap = 0
    for r in rq:
        if b.size and int(np.min(np.abs(b - r))) <= TOL_SAMPEL:
            tertangkap += 1
    jenis = []
    for x in b:
        dq = int(np.min(np.abs(rq - x))) if rq.size else 10 ** 9
        dt = int(np.min(np.abs(rt - x))) if rt.size else 10 ** 9
        if min(dq, dt) > TOL_SAMPEL:
            jenis.append("lain")
        else:
            jenis.append("qrs" if dq <= dt else "t")
    return dict(acuan=int(rq.size), tertangkap=int(tertangkap), hilang=int(rq.size - tertangkap),
                benar=int(jenis.count("qrs")), palsu=int(jenis.count("t") + jenis.count("lain")),
                palsu_t=int(jenis.count("t")), denyut=int(b.size))

