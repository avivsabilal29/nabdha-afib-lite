def jalankan_aturan_dua_domain(selubung, terfilter, puncak, lebar=LEBAR_PEAKF):
    """Aturan P3-5 pada satu rekaman, dengan search back hanya pada domain integrasi.

    Domain integrasi memakai ambang pertama persamaan (14), dan search back hanya membuka ambang
    kedua persamaan (15). Domain EKG terfilter memakai ambang pertama persamaan (19) dengan
    pembaruan persamaan (17), (18), dan (20). PEAKF adalah puncak EKG terfilter di sekitar kandidat.
    Karena search back tidak membuka ambang domain EKG terfilter, bobot cepat persamaan (21) hanya
    dikenakan pada denyut yang ditemukan lewat ambang kedua domain integrasi.
    """
    spki_i = npki_i = float(AWAL_I[0])
    spki_f = npki_f = float(AWAL_F[0])
    t1_i = npki_i + BOBOT_SELISIH * (spki_i - npki_i)
    t1_f = npki_f + BOBOT_SELISIH * (spki_f - npki_f)
    rr_terpilih, terakhir = [], None
    golongan = {"kedua domain": 0, "integrasi saja": 0, "terfilter saja": 0, "tidak ada": 0}
    n_searchback, n_ditolak = 0, 0
    for p in puncak:
        nilai_i = float(selubung[p])
        lo, hi = max(0, p - lebar), min(terfilter.size, p + lebar + 1)
        nilai_f = float(terfilter[lo:hi].max())
        lolos_i = bool(nilai_i > t1_i)
        lewat_searchback = False
        if not lolos_i and terakhir is not None and rr_terpilih:
            rr2 = float(np.mean(rr_terpilih[-8:]))
            if (p - terakhir) > RR_MISSED * rr2 * FS_BOARD and nilai_i > RASIO_AMBANG2 * t1_i:
                lolos_i = True
                lewat_searchback = True
                n_searchback += 1
        lolos_f = bool(nilai_f > t1_f)
        if lolos_i and lolos_f:
            nama = "kedua domain"
            bobot_i = BOBOT_LEWAT_AMBANG2 if lewat_searchback else BOBOT_NORMAL
            bobot_f = BOBOT_LEWAT_AMBANG2 if lewat_searchback else BOBOT_NORMAL
            spki_i = bobot_i * nilai_i + (1.0 - bobot_i) * spki_i
            spki_f = bobot_f * nilai_f + (1.0 - bobot_f) * spki_f
            if terakhir is not None:
                rr = (p - terakhir) / FS_BOARD
                rr2 = float(np.mean(rr_terpilih[-8:])) if rr_terpilih else rr
                if (not rr_terpilih) or (not irama_tidak_teratur(rr, rr2)):
                    rr_terpilih.append(rr)
            terakhir = p
        else:
            if lolos_i or lolos_f:
                n_ditolak += 1
            npki_i = BOBOT_NORMAL * nilai_i + (1.0 - BOBOT_NORMAL) * npki_i
            npki_f = BOBOT_NORMAL * nilai_f + (1.0 - BOBOT_NORMAL) * npki_f
            if lolos_i:
                nama = "integrasi saja"
            elif lolos_f:
                nama = "terfilter saja"
            else:
                nama = "tidak ada"
        golongan[nama] += 1
        t1_i = npki_i + BOBOT_SELISIH * (spki_i - npki_i)
        t1_f = npki_f + BOBOT_SELISIH * (spki_f - npki_f)
    return {"golongan": golongan, "ditolak": n_ditolak, "searchback": n_searchback,
            "diterima_kedua": golongan["kedua domain"],
            "diterima_integrasi": golongan["kedua domain"] + golongan["integrasi saja"],
            "diterima_terfilter": golongan["kedua domain"] + golongan["terfilter saja"],
            "t1_i_akhir": t1_i, "t1_f_akhir": t1_f}

