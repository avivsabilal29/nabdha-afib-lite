def rekursi_fixed_point(x_int, bits):
    """Bentuk recursive dengan accumulator yang wrap pada lebar `bits` bit."""
    lo, span = -(1 << (bits - 1)), (1 << bits)
    xb = x_int.astype(np.int64)
