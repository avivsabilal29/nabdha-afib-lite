def buat_denyut(rr_sampel_buat=200, hilang=(), n_denyut=60, amp=3.0, amp_hilang=1.0, sigma_sampel=7.5):
    """Selubung buatan bersatuan sampel, jarak denyut rr_sampel_buat, denyut pada indeks hilang dikecilkan."""
    durasi = 50 + n_denyut * rr_sampel_buat + 100
    n = durasi + 8
    env = np.zeros(n)
    for b in range(n_denyut):
        t0 = 50 + b * rr_sampel_buat
        a = amp_hilang if b in hilang else amp
        s = max(0, t0 - 30)
        e = min(n, t0 + 30)
        tt = np.arange(s, e)
        env[s:e] += a * np.exp(-((tt - t0) / sigma_sampel) ** 2.0)
    return env

