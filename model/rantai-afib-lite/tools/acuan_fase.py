# ===== SOURCE: t-wave-discrimination.ipynb | CELL 2 | def | selubung_bergantian =====
def selubung_bergantian(y3, geser=8):
    """Kuadrat persamaan (10) lalu integrasi jendela bergantian 37 dan 38 sampel, persamaan (11)."""
    d = y3 >> geser
    ku = d * d
    n = ku.size
    cs = np.zeros(n + 1, dtype=np.int64)
    np.cumsum(ku, out=cs[1:])
    sel = np.empty(n, dtype=np.int64)
    for i in range(n):
        w = N_A if (i % 2 == 0) else N_B
        a = i - w + 1
        if a < 0:
            a = 0
        sel[i] = cs[i + 1] - cs[a]
    return ku, sel

