    """jumlah puncak lokal di atas ambang relatif, di sekitar satu denyut"""
    s = v[max(0, i - radius): i + radius].astype(float)
    return int(np.sum((s[1:-1] >= s[:-2]) & (s[1:-1] > s[2:]) & (s[1:-1] > ambang * s.max())))

