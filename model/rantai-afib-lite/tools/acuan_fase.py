    kos_p = 0.05 * (1.0 + np.cos(np.pi * idx_p / hw_p))
    qrs, hw_q = pulsa_segitiga(AQ, HQ_MS / 1000.0)
    for t in mulai:
        if not hanya_t:
            tambah(x, t, qrs)
