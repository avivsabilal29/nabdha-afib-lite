    fr = np.sort(np.unique(df["fraksi penanda"].to_numpy()))
    kandidat = [0.0]
    kandidat.extend(((fr[:-1] + fr[1:]) / 2.0).tolist())
    kandidat.append(float(fr[-1]) + 0.5)
