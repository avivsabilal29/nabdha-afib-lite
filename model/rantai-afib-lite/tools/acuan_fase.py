def deret_teratur(n_denyut=60, amplitudo_qrs=4000, rerata_derau=150.0, seed=5):
    """Deret puncak teratur: satu puncak QRS tiap 250 sampel dan dua puncak derau di antaranya."""
    panjang = n_denyut * int(FS_BOARD)
    v = np.zeros(panjang, dtype=np.int64)
    rng_t = np.random.default_rng(seed)
    amp_derau = rng_t.exponential(rerata_derau, size=n_denyut * 2)
    for b in range(n_denyut):
        v[b * int(FS_BOARD) + 50] = int(amplitudo_qrs)
    for j in range(n_denyut * 2):
        pos = j * 125 + 120
        if pos < panjang:
            v[pos] = int(amp_derau[j])
    return v

