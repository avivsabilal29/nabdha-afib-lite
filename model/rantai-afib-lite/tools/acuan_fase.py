def update_bulat(nilai_lama, puncak, mode="floor"):
    """Satu pembaruan persamaan (12) atau (13) pada aritmetika bilangan bulat."""
    d = int(puncak) - int(nilai_lama)
    if mode == "floor":
        tambah = d >> 3
    else:
        tambah = int(np.trunc(d / 8.0))
    return int(nilai_lama) + int(tambah)

