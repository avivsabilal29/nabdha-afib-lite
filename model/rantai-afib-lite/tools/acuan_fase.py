def mag_H(f, fs):
    """Magnitude response |H| = (sin(3*omega)/sin(omega/2))^2, dengan f = 0 dipetakan ke DC gain 36."""
    f = np.asarray(f, dtype=float)
    w = 2.0 * np.pi * f / fs
    with np.errstate(divide="ignore", invalid="ignore"):
        r = np.sin(3.0 * w) / np.sin(w / 2.0)
    out = np.where(np.abs(f) < 1e-12, 36.0, r ** 2)
    return float(out) if out.ndim == 0 else out

