def auc_rank(x, y):
    x = np.asarray(x, float)
    y = np.asarray(y, float)
    r = np.argsort(np.concatenate([x, y])).argsort() + 1
    return float((r[:x.size].sum() - x.size * (x.size + 1) / 2) / (x.size * y.size))

