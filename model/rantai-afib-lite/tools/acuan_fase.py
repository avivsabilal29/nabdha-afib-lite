# GENERATED BINDING: the block below redefines rantai_tapis, so the phase 3 definition stays reachable as rantai_tapis__fase3
rantai_tapis__fase3 = rantai_tapis
def rantai_tapis(x):
    """Rantai terkunci: low-pass, high-pass rekursif, lalu turunan lima titik dibagi 8."""
    y1 = np.convolve(x, HLP, mode="full")[: x.size].astype(np.int64)
    d = 32 * geser_kiri(y1, 16) - y1 + geser_kiri(y1, 32)
    k = np.arange(y1.size, dtype=np.int64)
    y2 = (((-1) ** k) * np.cumsum(((-1) ** k) * d)).astype(np.int64)
    y3 = np.zeros_like(y2)
    y3[2:-2] = (y2[4:] + 2 * y2[3:-1] - 2 * y2[1:-3] - y2[:-4]) // 8
    return y1, y2, y3

