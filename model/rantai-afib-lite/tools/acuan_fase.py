def median_bulat(v):
    """Median bilangan bulat. Untuk jumlah anggota genap dipakai rata-rata dua nilai tengah, tetap bilangan
    bulat karena seluruh interval RR bersatuan sampel adalah bilangan bulat."""
    s = np.sort(np.asarray(v, dtype=np.int64))
    if s.size % 2 == 1:
        return int(s[s.size // 2])
    return int((s[s.size // 2 - 1] + s[s.size // 2]) // 2)

