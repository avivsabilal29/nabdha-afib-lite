class PenampanPuncak:
    """Penampan puncak kandidat untuk prosedur search back, sesuai kalimat makalah yang menyebut puncak
    terbesar yang tersimpan di antara dua ambang. Kedalaman penampan tetap dan pemakaiannya dicacah,
    sehingga jumlah puncak yang tersimpan sekaligus dapat dipertanggungjawabkan. Isi penampan hanya
    dibaca oleh operasi terbesar lalu dikosongkan, jadi kedalaman yang lebih kecil pun memberi hasil yang
    sama selama puncak terbesar tetap tersimpan, dan pembuangan kandidat dicacah supaya perbedaan itu
    terlihat."""

    def __init__(self, kedalaman):
        self.kedalaman = int(kedalaman)
        self.posisi = np.zeros(self.kedalaman, dtype=np.int64)
        self.nilai = np.zeros(self.kedalaman, dtype=np.int64)
        self.isi = 0
        self.pemakaian_terbesar = 0
        self.dibuang = 0

    def kosongkan(self):
        """Kosongkan penampan setelah puncak terbesar dibaca atau setelah denyut ditemukan."""
        self.isi = 0

    def tambah(self, posisi, nilai):
        """Simpan satu puncak kandidat. Bila penampan penuh, puncak terlemah dibuang supaya puncak
        terbesar tetap tersimpan, dan pembuangan itu dicacah."""
        nilai = int(nilai)
        if self.isi < self.kedalaman:
            self.posisi[self.isi] = int(posisi)
            self.nilai[self.isi] = nilai
            self.isi += 1
        else:
            lemah = int(np.argmin(self.nilai[: self.isi]))
            if nilai > int(self.nilai[lemah]):
                self.posisi[lemah] = int(posisi)
                self.nilai[lemah] = nilai
            self.dibuang += 1
        if self.isi > self.pemakaian_terbesar:
            self.pemakaian_terbesar = self.isi

    def terbesar(self):
        """Kembalikan pasangan (posisi, nilai) puncak terbesar, atau None bila penampan kosong."""
        if self.isi == 0:
            return None
        j = int(np.argmax(self.nilai[: self.isi]))
        return int(self.posisi[j]), int(self.nilai[j])

    def __len__(self):
        return self.isi

# ===== SOURCE: rr-interval-averaging-equations.ipynb | CELL 3 | def | lolos_bawah =====
def lolos_bawah(rr, pecahan, pembilang, penyebut):
    """Uji rr lebih besar atau sama dengan (p bagi q) kali (B bagi m) sebagai silang q m rr >= p B.
    Seluruhnya bilangan bulat, jadi tidak ada pembagian dan tidak ada galat pembulatan titik mengambang."""
    p, q = pecahan
    return q * penyebut * rr >= p * pembilang

# ===== SOURCE: rr-interval-averaging-equations.ipynb | CELL 3 | def | lolos_atas =====
def lolos_atas(rr, pecahan, pembilang, penyebut):
    """Uji rr lebih kecil atau sama dengan (p bagi q) kali (B bagi m) sebagai silang q m rr <= p B."""
    p, q = pecahan
    return q * penyebut * rr <= p * pembilang

# ===== SOURCE: rr-interval-averaging-equations.ipynb | CELL 3 | def | lewat_missed =====
def lewat_missed(rr, pecahan, pembilang, penyebut):
    """Uji rr lebih besar dari (p bagi q) kali (B bagi m) sebagai silang q m rr > p B."""
    p, q = pecahan
    return q * penyebut * rr > p * pembilang

