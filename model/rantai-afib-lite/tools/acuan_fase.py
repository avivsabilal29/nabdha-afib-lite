def puncak_adaptif(S, F, bentuk=None, kedalaman=KEDALAMAN_PENAMPAN, lrn_s=2.0, refr_ms=200.0):
    """Pemetik puncak pembanding: ambang adaptif (14) sampai (21) plus search back (28) dengan penampan
    puncak kandidat kedalaman tetap. Keluaran kamus berkunci puncak, rr, n_cari, n_angkat, penampan."""
    if bentuk is None:
        bentuk = BENTUK_BAWAAN
    Sf = S.astype(np.int64)
    Ff = np.abs(F).astype(np.int64)
    n = Sf.size
    lrn = int(lrn_s * FS)
    refr = int(refr_ms / 1000.0 * FS)
    kand = np.flatnonzero((Sf[1:-1] > Sf[:-2]) & (Sf[1:-1] >= Sf[2:])) + 1
    kand = kand[Sf[kand] > 0]
    SP, NP = Sf[:lrn].max() / 3.0, Sf[:lrn].mean() / 2.0
    SPF, NPF = Ff[:lrn].max() / 3.0, Ff[:lrn].mean() / 2.0
    penampan = PenampanPuncak(kedalaman)
    det, rr, last = [], [], -refr
    n_cari, n_angkat = 0, 0
    B2, m2 = None, None
    tidak_teratur = False
    for i in kand:
        i = int(i)
        thi1 = NP + 0.25 * (SP - NP)
        thf1 = NPF + 0.25 * (SPF - NPF)
        if tidak_teratur:                      # persamaan (22) dan (23)
            thi1 = 0.5 * thi1
            thf1 = 0.5 * thf1
        thi2, thf2 = 0.5 * thi1, 0.5 * thf1
        if B2 is not None and bool(lewat_missed(i - last, bentuk["missed"], B2, m2)):
            n_cari += 1
            kandidat = penampan.terbesar()
            if kandidat is not None:
                p, v = kandidat
                if v > thi2 and float(Ff[p]) > thf2:
                    det.append(p)
                    rr.append(p - last)
                    last = p
                    SP = 0.25 * v + 0.75 * SP
                    SPF = 0.25 * float(Ff[p]) + 0.75 * SPF
                    n_angkat += 1
            penampan.kosongkan()
        if i - last < refr:
            continue
        lo, hi = max(0, i - 20), min(n, i + 21)
        jf = lo + int(np.argmax(Ff[lo:hi]))
        fv = Ff[jf]
        if Sf[i] > thi1 and fv > thf1:
            det.append(jf)
            if det[:-1]:
                rr.append(jf - last)
            last = jf
            SP = 0.125 * Sf[i] + 0.875 * SP
            SPF = 0.125 * fv + 0.875 * SPF
            penampan.kosongkan()
        else:
            if Sf[i] > thi2 and fv > thf2:
                penampan.tambah(i, Sf[i])
            NP = 0.125 * Sf[i] + 0.875 * NP
            NPF = 0.125 * fv + 0.875 * NPF
        if len(rr) >= DELAPAN:
            avg1 = float(np.mean(rr[-DELAPAN:]))
            if B2 is None:
                B2, m2 = int(sum(rr[-DELAPAN:])), DELAPAN
            dalam = [v for v in rr[-DELAPAN:]
                     if bool(lolos_bawah(v, bentuk["bawah"], B2, m2))
                     and bool(lolos_atas(v, bentuk["atas"], B2, m2))]
            if dalam:
                B2, m2 = int(sum(dalam[-DELAPAN:])), len(dalam[-DELAPAN:])
            tidak_teratur = len(dalam) < DELAPAN
    return dict(puncak=np.array(sorted(det)), rr=np.array(rr), n_cari=n_cari,
                n_angkat=n_angkat, penampan=penampan)

