def ukur_lolos_ambang(v, potong_separuh):
    """Hitung puncak yang lolos ambang kedua dan ambang pertama sepanjang deret."""
    puncak = deteksi_puncak(v)
    awal_v, _ = nilai_awal_taksiran(v)
    spki, npki = float(awal_v), float(awal_v)
    t1 = npki + BOBOT_SELISIH * (spki - npki)
    t2 = RASIO_AMBANG2 * t1
    lolos1, lolos2, t1min, t2min = 0, 0, None, None
    for p in puncak:
        nilai = float(v[p])
        if nilai > t1:
            lolos1 += 1
            spki = BOBOT_NORMAL * nilai + (1.0 - BOBOT_NORMAL) * spki
        else:
            npki = BOBOT_NORMAL * nilai + (1.0 - BOBOT_NORMAL) * npki
        if t2 < nilai <= t1:
            lolos2 += 1
        t1 = npki + BOBOT_SELISIH * (spki - npki)
        if potong_separuh:
            t1 = 0.5 * t1
        t2 = RASIO_AMBANG2 * t1
        t1min = t1 if t1min is None else min(t1min, t1)
        t2min = t2 if t2min is None else min(t2min, t2)
    return {"puncak": len(puncak), "lolos1": lolos1, "lolos2": lolos2,
            "t1min": t1min, "t2min": t2min, "t1akhir": t1, "t2akhir": t2}

