def nilai_awal_taksiran(deret, n_awal=SAMPEL_INISIALISASI):
    """P3-1: nilai awal SPKI dan NPKI adalah maksimum dua detik pertama deret.

    Pada 250 Hz, dua detik pertama adalah 500 sampel pertama. Untuk deret puncak, dua detik pertama
    dinyatakan sebagai jumlah puncak pertama yang setara, dan jumlah itu dicetak di sel pemakainya.
    Kedua taksiran mulai dari nilai yang sama, sehingga ambang pertama mulai dari maksimum itu.
    """
    potong = np.asarray(deret)
    if potong.size > n_awal:
        potong = potong[: n_awal]
    awal = int(potong.max())
    return awal, awal

