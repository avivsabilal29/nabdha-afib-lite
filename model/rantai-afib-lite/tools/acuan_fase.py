    terpakai = np.zeros(n, dtype=bool)
    for a in range(0, n, blok):
        b = min(n, a + blok)
        seg = Sf[a:b]
        thr = frac * np.percentile(seg, persen)
        loc = np.flatnonzero((seg[1:-1] > seg[:-2]) & (seg[1:-1] >= seg[2:])) + 1
        loc = loc[seg[loc] > thr]
        for i in loc[np.argsort(-seg[loc])]:
            p = a + int(i)
            lo, hi = max(0, p - refr), min(n, p + refr + 1)
            if terpakai[lo:hi].any():
                continue
            terpakai[lo:hi] = True
            terima.append(p)
    return np.array(sorted(terima))

