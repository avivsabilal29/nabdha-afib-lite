# ===== SOURCE: t-wave-discrimination.ipynb | CELL 15 | def | pulsa_segitiga =====
def pulsa_segitiga(amp, hw_s):
    hw = int(round(hw_s * FS))
    idx = np.arange(-hw, hw + 1)
    return amp * (1.0 - np.abs(idx) / hw), hw

# ===== SOURCE: t-wave-discrimination.ipynb | CELL 15 | def | tambah =====
def tambah(x, pos, y):
    a = max(0, int(pos))
    b = min(x.size, a + y.size)
    x[a:b] += y[:b - a]

