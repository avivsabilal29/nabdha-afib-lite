def dalam_batas(rr, pembilang, penyebut):
    """Dua batas RR fase 4, bentuk silang eksak 23 per 25 dan 29 per 25 pada bilangan bulat."""
    return (25 * penyebut * rr >= 23 * pembilang) and (25 * penyebut * rr <= 29 * pembilang)

# ===== SOURCE: t-wave-discrimination.ipynb | CELL 2 | class | TahapRR =====
class TahapRR:
    """Persamaan (24) sampai (29) ditambah aturan penyemaian ulang P4-5.

    Bila tidak ada interval RR yang lolos pita 0,92 sampai 1,16 kali rata-rata kedua selama 8 denyut
    berturut-turut, antrean delapan interval diisi ulang memakai median 32 interval RR terakhir, lalu
    rata-rata kedua dihitung ulang dari antrean itu. Penyemaian ulang dibatasi paling banyak sekali
    per 8 denyut.
    """

    def __init__(self, semai_aktif=True):
        self.semai_aktif = bool(semai_aktif)
        self.deret = []               # delapan interval RR terakhir
        self.antre = []               # delapan interval lolos terakhir, rata-rata kedua
        self.riwayat = []             # sampai SEMAI_PANJANG interval RR terakhir
        self.gagal = 0                # denyut berturut tanpa interval lolos
        self.jeda = SEMAI_JEDA        # denyut sejak penyemaian ulang terakhir
        self.semai = 0                # jumlah penyemaian ulang
        self.menyala = 0              # penanda irama teratur, persamaan (29)
        self.ra1 = 0.0
        self.ra2 = 0.0

    def maju(self, rr):
        """Satu langkah denyut. Keluaran: menyala dan penanda penyemaian ulang langkah ini."""
        rr = int(rr)
        self.deret.append(rr)
        if len(self.deret) > DELAPAN:
            self.deret.pop(0)
        self.riwayat.append(rr)
        if len(self.riwayat) > SEMAI_PANJANG:
            self.riwayat.pop(0)
        if len(self.deret) < DELAPAN:
            return 0, 0
        self.ra1 = float(int(sum(self.deret)) >> 3)
        pembilang = int(sum(self.antre))
        penyebut = len(self.antre)
        acuan = pembilang if penyebut > 0 else int(round(self.ra1))
        acuan_penyebut = penyebut if penyebut > 0 else 1
        lolos = dalam_batas(rr, acuan, acuan_penyebut)
        if lolos:
            self.gagal = 0
        else:
            self.gagal += 1
        self.jeda += 1
        disemai = 0
        if self.semai_aktif and self.gagal >= DELAPAN and self.jeda >= SEMAI_JEDA:
            tengah = int(np.median(self.riwayat))
            self.antre = [tengah] * DELAPAN
            self.semai += 1
            disemai = 1
            self.gagal = 0
            self.jeda = 0
        elif lolos:
            self.antre.append(rr)
            if len(self.antre) > DELAPAN:
                self.antre.pop(0)
        pembilang = int(sum(self.antre))
        penyebut = len(self.antre)
        self.ra2 = float(pembilang) / float(penyebut) if penyebut > 0 else float(self.ra1)
        self.menyala = 0
        if penyebut == DELAPAN:
            self.menyala = 1
            for r in self.deret:
                if not dalam_batas(r, pembilang, penyebut):
                    self.menyala = 0
                    break
        return int(self.menyala), int(disemai)

# ===== SOURCE: t-wave-discrimination.ipynb | CELL 2 | def | jalankan =====
def jalankan(sel, puncak, hp, besaran=BESARAN_BAWAAN, mode_half="tidak", aturan_t=ATURAN_T_BAWAAN,
             setengah=SETENGAH_JENDELA, pantul=PANTUL, topeng=(250, 2000), jendela_f=25,
             semai_aktif=True):
    """Tahap ambang persamaan (12) sampai (23) ditambah aturan gelombang T halaman 234.

    aturan_t bawaan hidup, sesuai P5-1. aturan_t False hanya dipakai sebagai keadaan pembanding.
    besaran bawaan keluaran turunan lima titik, sesuai P5-2.
    semai_aktif bawaan hidup mengikuti aturan penyemaian ulang P4-5; nilai False hanya pembanding.
    """
    deret_kemiringan = deret_besaran(besaran)
    absf = np.abs(hp)
    n_sel = sel.size
    pk_f = np.zeros(puncak.size, dtype=np.int64)
    kem = np.zeros(puncak.size, dtype=np.int64)
    for i, p in enumerate(puncak):
        a = max(0, int(p) - jendela_f)
        b = min(n_sel, int(p) + jendela_f + 1)
        pk_f[i] = int(absf[a:b].max())
        kem[i] = kemiringan(deret_kemiringan, int(p), setengah)
    SPKI = NPKI = SPKF = NPKF = 0
    qrs, rr_ms, tolakan = [], [], []
    tahap = TahapRR(semai_aktif=semai_aktif)
    penanda = langkah = calon_kedua = cari_mundur = 0
    i_qrs = None
    menyala_last = 0
    kem_qrs = None
    diperiksa = ditolak = diterima_pita = 0
    rasio_pita, rasio_qrs = [], []
    berisiko = 0

    def catat(sp):
        nonlocal i_qrs, penanda, langkah, menyala_last
        qrs.append(sp)
        i_qrs = sp
        if len(qrs) >= 2:
            rr = (qrs[-1] - qrs[-2]) * 1000 // int(FS)
            rr_ms.append(rr)
            if topeng[0] <= rr <= topeng[1]:
                menyala_last, _ = tahap.maju(rr)
                penanda += menyala_last
                langkah += 1

    for i, p in enumerate(puncak):
        p = int(p)
        I1 = NPKI + bagi_empat(SPKI - NPKI)
        F1 = NPKF + bagi_empat(SPKF - NPKF)
        if mode_half == "paksa" or (mode_half == "lingkar" and menyala_last != 1):
            I1 = I1 >> 1
            F1 = F1 >> 1
        I2 = I1 >> 1
        pv = int(sel[p])
        sinyal = pv > I1
        if sinyal and i_qrs is not None and (p - i_qrs) < pantul:
            sinyal = False                       # gerbang refraktori 200 milidetik
        if aturan_t and sinyal and i_qrs is not None and kem_qrs is not None:
            dt_ms = (p - i_qrs) * 1000.0 / FS
            if dt_ms < PITA_MS[1]:               # jendela 360 milidetik
                diperiksa += 1
                rasio_pita.append(float(kem[i]) / float(kem_qrs) if kem_qrs > 0 else float("inf"))
                if uji_setengah(int(kem[i]), int(kem_qrs)):
                    sinyal = False
                    ditolak += 1
                    tolakan.append((p, int(kem[i]), int(kem_qrs),
                                    float(kem[i]) / float(kem_qrs) if kem_qrs > 0 else float("inf"),
                                    dt_ms))
                else:
                    diterima_pita += 1
        if not sinyal and pv > I2:
            calon_kedua += 1
        if sinyal:
            SPKI = SPKI + bagi_delapan(pv - SPKI)
            if pk_f[i] > F1:
                SPKF = SPKF + bagi_delapan(pk_f[i] - SPKF)
            else:
                NPKF = NPKF + bagi_delapan(pk_f[i] - NPKF)
            if i_qrs is not None and kem_qrs is not None:
                if (p - i_qrs) * 1000.0 / FS < PITA_MS[1]:
                    rasio_qrs.append(float(kem[i]) / float(kem_qrs) if kem_qrs > 0 else float("inf"))
                    if kem_qrs > 0 and uji_setengah(int(kem[i]), int(kem_qrs)):
                        berisiko += 1
            kem_qrs = int(kem[i])
            catat(p)
            continue
        NPKI = NPKI + bagi_delapan(pv - NPKI)
        NPKF = NPKF + bagi_delapan(pk_f[i] - NPKF)
        if i_qrs is not None:
            ra2_pakai = tahap.ra2 if tahap.ra2 > 0 else tahap.ra1
            if ra2_pakai > 0:
                batas = 83.0 * ra2_pakai / 50.0
                if (p - i_qrs) * 1000.0 / FS > batas:
                    a = int(np.searchsorted(puncak, i_qrs)) + 1
                    best = None
                    for j in range(a, i + 1):
                        v = int(sel[puncak[j]])
                        if I2 < v <= I1 and (best is None or v > best[1]):
                            best = (int(puncak[j]), v, int(pk_f[j]), int(kem[j]))
                    if best is not None:
                        sp, v, vf, vk = best
                        cari_mundur += 1
                        if vf > F1:
                            SPKF = SPKF + bagi_empat(vf - SPKF)
                        else:
                            NPKF = NPKF + bagi_empat(vf - NPKF)
                        SPKI = SPKI + bagi_empat(v - SPKI)
                        kem_qrs = vk
                        catat(sp)
    return dict(qrs=qrs, rr_ms=rr_ms, penanda=penanda, langkah=langkah, calon_kedua=calon_kedua,
                cari_mundur=cari_mundur, diperiksa=diperiksa, ditolak=ditolak,
                diterima_pita=diterima_pita, rasio_pita=np.array(rasio_pita, dtype=float),
                rasio_qrs=np.array(rasio_qrs, dtype=float), berisiko=berisiko,
                tolakan=tolakan, kem=kem, pk_f=pk_f, semai=tahap.semai,
                ra2_akhir=tahap.ra2, menyala_akhir=tahap.menyala)

