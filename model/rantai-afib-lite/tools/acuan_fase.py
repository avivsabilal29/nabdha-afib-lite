# ===== SOURCE: squaring-and-moving-window-integrator-equation.ipynb | CELL 8 | def | tunda_beda_fasa =====
def tunda_beda_fasa(y, f_uji=2.0):
    """tundaan dalam sampel, diukur dari beda fasa keluaran terhadap sinusoida masukan pada pita lolos"""
    n_urut = np.arange(y.size)
    w_uji = 2.0 * np.pi * f_uji / FS_BOARD
    potong = slice(2000, y.size - 2000)
    a = 2.0 * np.mean(y[potong] * np.cos(w_uji * n_urut[potong]))
    b = 2.0 * np.mean(y[potong] * np.sin(w_uji * n_urut[potong]))
    return float(np.arctan2(-a, b) / w_uji)

