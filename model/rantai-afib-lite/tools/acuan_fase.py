# ===== SOURCE: t-wave-discrimination.ipynb | CELL 2 | def | uji_setengah =====
def uji_setengah(s, s_prev, bentuk=UJI_SETENGAH_BAWAAN):
    """Uji halaman 234 pada bilangan bulat. Bawaan P5-3 bentuk silang, geseran hanya pembanding."""
    if bentuk == "silang":
        return 2 * s < s_prev
    if bentuk == "geser":
        return s < (s_prev >> 1)
    if bentuk == "geser_bulat":
        return s < ((s_prev + 1) >> 1)
    raise ValueError("bentuk uji tidak dikenal")

