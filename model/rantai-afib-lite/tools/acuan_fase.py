def rantai_tapis(x):
    """Rantai terkunci: low-pass persamaan (3), high-pass persamaan (6), turunan (9) bagi 8."""
    n = x.size
    y1 = np.zeros(n, dtype=np.int64)
    for i in range(n):
        y1[i] = (2 * y1[i - 1] if i >= 1 else 0) - (y1[i - 2] if i >= 2 else 0) + x[i] \
            - (2 * x[i - 6] if i >= 6 else 0) + (x[i - 12] if i >= 12 else 0)
    y2 = np.zeros(n, dtype=np.int64)
    for i in range(n):
        y2[i] = (32 * y1[i - 16] if i >= 16 else 0) \
            - ((y2[i - 1] if i >= 1 else 0) + y1[i] - (y1[i - 32] if i >= 32 else 0))
    y3 = np.zeros(n, dtype=np.int64)
    for i in range(n):
        s = 2 * y2[i]
        s += y2[i - 1] if i >= 1 else 0
        s -= y2[i - 3] if i >= 3 else 0
        s -= 2 * y2[i - 4] if i >= 4 else 0
        y3[i] = s // 8 if s >= 0 else -((-s) // 8)
    return y1, y2, y3

