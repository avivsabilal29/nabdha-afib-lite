def shift_pad(x_in, k):
    '''x[n-k] dengan index di luar array dianggap 0'''
    x_in = np.asarray(x_in, dtype=float)
    n_len = x_in.size
    if k <= 0:
        return x_in.copy()
    if k >= n_len:
        return np.zeros(n_len)
    return np.concatenate([np.zeros(k), x_in[:n_len - k]])

