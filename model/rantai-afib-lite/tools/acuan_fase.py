def jalankan_search_back(env, rr_avg2=200, bentuk=None, I1=1.5, I2=0.75, refr=REFR_SAMPEL,
                         kedalaman=KEDALAMAN_PENAMPAN):
    """Prosedur search back bersatuan sampel dengan penampan puncak kandidat. Jarak ke denyut terakhir
    diuji terhadap batas missed lewat perkalian silang bulat, tanpa pembagian."""
    if bentuk is None:
        bentuk = BENTUK_BAWAAN
    n = env.size
    penampan = PenampanPuncak(kedalaman)
    last = -10 ** 12
    deteksi = []
    diangkat = []
    pemeriksaan = 0
    menunggu = False
    for i in range(1, n - 1):
        if bool(lewat_missed(i - last, bentuk["missed"], rr_avg2, 1)):
            kandidat = penampan.terbesar()
            if kandidat is not None:
                p, v = kandidat
                diangkat.append((p, v, i))
                deteksi.append(p)
                last = p
                penampan.kosongkan()
                menunggu = False
            elif not menunggu:
                pemeriksaan += 1
                menunggu = True
        if env[i] > env[i - 1] and env[i] >= env[i + 1] and env[i] > I2:
            if i - last < refr:
                continue
            if env[i] > I1:
                deteksi.append(i)
                last = i
                penampan.kosongkan()
                menunggu = False
            else:
                penampan.tambah(i, env[i])
    return np.array(sorted(deteksi)), diangkat, pemeriksaan, penampan

