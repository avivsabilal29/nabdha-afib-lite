def keputusan_gerbang(df, ambang):
    """Keputusan gerbang satu jendela: fraksi penanda di bawah ambang berarti tidak teratur yaitu AFIB,
    fraksi penanda mencapai ambang berarti teratur yaitu N."""
    teratur = df["fraksi penanda"].to_numpy() >= ambang
    kelas = df["kelas"].to_numpy()
    tp = int(np.sum((kelas == "AFIB") & ~teratur))
    fn = int(np.sum((kelas == "AFIB") & teratur))
    fp = int(np.sum((kelas == "N") & ~teratur))
    tn = int(np.sum((kelas == "N") & teratur))
    return dict(TP=tp, FN=fn, FP=fp, TN=tn,
                kepekaan=tp / max(tp + fn, 1),
                spesifisitas=tn / max(tn + fp, 1),
                akurasi=(tp + tn) / max(df.shape[0], 1))

