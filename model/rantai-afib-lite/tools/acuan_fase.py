# ===== SOURCE: squaring-and-moving-window-integrator-equation.ipynb | CELL 4 | def | jendela_bergantian =====
def jendela_bergantian(x, na=N_ALT_A, nb=N_ALT_B):
    """Bentuk langsung dengan lebar bergantian na dan nb, acuan pemeriksaan penampan melingkar."""
    pre = np.concatenate([[0], np.cumsum(x.astype(np.int64))])
    idx = np.arange(x.size)
    lebar = np.where(idx % 2 == 0, na, nb)
    return pre[idx + 1] - pre[np.maximum(idx - lebar + 1, 0)]

# ===== SOURCE: squaring-and-moving-window-integrator-equation.ipynb | CELL 4 | def | selubung_bawaan =====
def selubung_bawaan(x, na=N_ALT_A, nb=N_ALT_B):
    """Selubung jendela bergantian lewat penampan melingkar, struktur jendela yang dikunci.

    Akumulator memegang lebar terbesar, satu tambah dan satu kurang per sampel.
    Keluaran lebar sempit dibentuk satu kurang tambahan di jalur keluaran, tanpa
    mengubah keadaan akumulator.
    """
    x = np.asarray(x)
    lebar_maks = int(max(na, nb))
    buf = np.zeros(lebar_maks, dtype=x.dtype)
    dtype = np.int64 if x.dtype.kind in "iu" else np.float64
    S = np.zeros(x.size, dtype=dtype)
    head = 0
    acc = np.zeros((), dtype=dtype)
    tambah = 0
    kurang = 0
    kurang_keluaran = 0
    for n in range(x.size):
        lebar = na if n % 2 == 0 else nb
        baru = np.asarray(x[n], dtype=dtype)
        keluar = np.asarray(buf[head], dtype=dtype)     # sampel tertua, x[n - lebar_maks]
        acc = acc + baru - keluar
        tambah += 1
        kurang += 1
        buf[head] = x[n]
        head = (head + 1) % lebar_maks                  # buf[head] kini x[n - lebar_maks + 1]
        if lebar < lebar_maks:
            S[n] = acc - np.asarray(buf[head], dtype=dtype)
            kurang_keluaran += 1
        else:
            S[n] = acc
    return S, tambah, kurang, kurang_keluaran

