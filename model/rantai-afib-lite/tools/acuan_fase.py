def tata_cara_ambang(selubung, puncak, mode_potong="kriteria"):
    """Persamaan (12) sampai (15) ditambah search back, dipakai bagian ini dan bagian berikutnya.

    mode_potong bernilai "tetap" untuk tanpa pemotongan separuh, "aktif" untuk pemotongan yang
    berjalan terus, dan "kriteria" untuk pemotongan yang dipicu tetapan P3-3. Nilai awal kedua
    taksiran memakai P3-1. Keadaan irama melekat sampai selang RR berikutnya diukur.
    """
    spki = npki = float(AWAL_I[0])
    t1 = npki + BOBOT_SELISIH * (spki - npki)
    rr_terpilih, terakhir = [], None
    tidak_teratur = False
    n_qrs, n_searchback, n_lolos2 = 0, 0, 0
    n_jendela, n_jendela_buru, n_potong = 0, 0, 0
    t1_min, t2_min = None, None
    t1_min_tunak, t2_min_tunak = None, None
    jejak_t1, jejak_t2 = [], []
    for n_iter, p in enumerate(puncak):
        nilai = float(selubung[p])
        qrs = False
        if nilai > t1:
            qrs = True
            spki = BOBOT_NORMAL * nilai + (1.0 - BOBOT_NORMAL) * spki
        else:
            if RASIO_AMBANG2 * t1 < nilai <= t1:
                n_lolos2 += 1
            if terakhir is not None and rr_terpilih:
                rr2 = float(np.mean(rr_terpilih[-8:]))
                if (p - terakhir) > RR_MISSED * rr2 * FS_BOARD and nilai > RASIO_AMBANG2 * t1:
                    qrs = True
                    n_searchback += 1
                    spki = BOBOT_LEWAT_AMBANG2 * nilai + (1.0 - BOBOT_LEWAT_AMBANG2) * spki
        if qrs:
            n_qrs += 1
            if terakhir is not None:
                rr = (p - terakhir) / FS_BOARD
                if rr_terpilih:
                    rr2 = float(np.mean(rr_terpilih[-8:]))
                    tidak_teratur = irama_tidak_teratur(rr, rr2)
                    n_jendela += 1
                    if tidak_teratur:
                        n_jendela_buru += 1
                else:
                    tidak_teratur = False
                if not tidak_teratur:
                    rr_terpilih.append(rr)
            terakhir = p
        else:
            npki = BOBOT_NORMAL * nilai + (1.0 - BOBOT_NORMAL) * npki
        t1 = npki + BOBOT_SELISIH * (spki - npki)
        potong = (mode_potong == "aktif") or (mode_potong == "kriteria" and tidak_teratur)
        if potong:
            t1 = 0.5 * t1
            n_potong += 1
        t2 = RASIO_AMBANG2 * t1
        t1_min = t1 if t1_min is None else min(t1_min, t1)
        t2_min = t2 if t2_min is None else min(t2_min, t2)
        if n_iter >= WARMUP_AFDB:
            t1_min_tunak = t1 if t1_min_tunak is None else min(t1_min_tunak, t1)
            t2_min_tunak = t2 if t2_min_tunak is None else min(t2_min_tunak, t2)
        jejak_t1.append(t1)
        jejak_t2.append(t2)
    return {"n_qrs": n_qrs, "n_searchback": n_searchback, "n_lolos2": n_lolos2,
            "n_jendela": n_jendela, "n_jendela_tidak_teratur": n_jendela_buru, "n_potong": n_potong,
            "t1_min": t1_min, "t2_min": t2_min, "t1_akhir": t1, "t2_akhir": t2,
            "t1_min_tunak": t1_min_tunak, "t2_min_tunak": t2_min_tunak,
            "jejak_t1": np.array(jejak_t1), "jejak_t2": np.array(jejak_t2)}

