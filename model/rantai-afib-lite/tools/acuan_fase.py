def jalankan_ambang(deret, mode="floor", halving=False, cara_init="maksimum dua detik",
                    n_awal=SAMPEL_INISIALISASI):
    """Jalankan persamaan (12) sampai (15) pada satu deret puncak, dengan pilihan mode bulat.

    cara_init bernilai "maksimum dua detik", yaitu P3-1, atau "nol", yaitu cara lama yang dipakai
    sebagai pembanding di bagian keputusan terkunci. Kedua jalur, bulat dan pecahan, memakai nilai
    awal yang sama supaya galatnya terukur pada titik berangkat yang sama.
    """
    if cara_init == "nol":
        spki, npki = 0, 0
    else:
        spki, npki = nilai_awal_taksiran(deret, n_awal)
    spki_p, npki_p = float(spki), float(npki)
    t1 = float(npki) + BOBOT_SELISIH * (float(spki) - float(npki))
    t2 = RASIO_AMBANG2 * t1
    baris = []
    for n, p in enumerate(deret, start=1):
        p = int(p)
        jenis = "sinyal" if p > t1 else "derau"
        if jenis == "sinyal":
            spki = update_bulat(spki, p, mode)
            spki_p = update_pecahan(spki_p, p)
        else:
            npki = update_bulat(npki, p, mode)
            npki_p = update_pecahan(npki_p, p)
        t1 = npki + BOBOT_SELISIH * (spki - npki)
        if halving:
            t1 = 0.5 * t1
        t2 = RASIO_AMBANG2 * t1
        baris.append({"n": n, "PEAKI": p, "jenis": jenis, "SPKI": spki, "NPKI": npki,
                      "SPKI pecahan": spki_p, "NPKI pecahan": npki_p,
                      "THRESHOLD_I1": t1, "THRESHOLD_I2": t2})
    return pd.DataFrame(baris)

