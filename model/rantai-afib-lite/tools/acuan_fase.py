def tabel_jendela(x_in, n_jendela):
    """tabel contoh soal, satu kolom per suku jendela, jumlahnya, dan keluaran sesudah dibagi n_jendela"""
    def xv(i):
        return 0 if i < 0 or i >= x_in.size else int(x_in[i])
    baris = []
    for n in range(x_in.size):
        suku = [xv(n - k) for k in range(n_jendela)]
        jumlah = int(np.sum(suku))
        baris.append({"n": n, "x[n]": suku[0], "x[n-1]": suku[1], "x[n-2]": suku[2], "x[n-3]": suku[3],
                      "x[n-4]": suku[4], "S[n]": jumlah,
                      "y[n] = S[n]/%d" % n_jendela: jumlah / float(n_jendela)})
    return pd.DataFrame(baris)

