def jejak_pecahan(puncak, bobot, panjang):
    """Jejak taksiran pada acuan pecahan murni, mulai dari nol."""
    nilai, jalur = 0.0, []
    for _ in range(panjang):
        nilai = bobot * puncak + (1.0 - bobot) * nilai
        jalur.append(nilai)
    return np.array(jalur)

