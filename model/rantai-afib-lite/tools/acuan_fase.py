def respons_jendela(N, f):
    """magnitudo respons jendela rata-rata panjang N pada frekuensi f"""
    w = 2.0 * np.pi * f / FS_BOARD
    with np.errstate(divide="ignore", invalid="ignore"):
        return float(abs(np.sin(N * w / 2.0) / (N * np.sin(w / 2.0))))

