def puncak_radius(sel, r=27):
    """Pemetik puncak selubung: puncak lokal dengan jarak minimum r sampel."""
    n = sel.size
    pk = []
    i = r
    while i < n - r:
        if sel[i] >= sel[i - r:i + r + 1].max() and sel[i] > 0:
            pk.append(i)
            i += r
        else:
            i += 1
    return np.array(pk, dtype=np.int64)

