# ===== SOURCE: squaring-and-moving-window-integrator-equation.ipynb | CELL 4 | def | geser_kiri =====
def geser_kiri(x, k):
    """x[n-k], indeks di luar larik dianggap nol, hasilnya bilangan bulat."""
    y = np.zeros_like(x)
    if k < len(x):
        y[k:] = x[: len(x) - k]
    return y

# ===== SOURCE: squaring-and-moving-window-integrator-equation.ipynb | CELL 4 | def | rantai_tapis =====
def rantai_tapis(x):
    """Rantai bilangan bulat terkunci: low-pass, high-pass, lalu turunan lima titik."""
    y1 = np.convolve(x, HLP, mode="full")[: x.size].astype(np.int64)
    d = 32 * geser_kiri(y1, 16) - y1 + geser_kiri(y1, 32)
    k = np.arange(y1.size, dtype=np.int64)
    y2 = (((-1) ** k) * np.cumsum(((-1) ** k) * d)).astype(np.int64)
    y3 = np.zeros_like(y2)
    y3[2:-2] = (y2[4:] + 2 * y2[3:-1] - 2 * y2[1:-3] - y2[:-4]) // 8
    return y1, y2, y3

